#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.9"
# dependencies = [
#     "cryptography>=42",
#     "pyserial>=3.5",
# ]
# ///
"""Regenerate test/interop_vectors.hpp from test/server.py.

    uv run test/gen_interop_vectors.py

The vector is the exact line server.py sends for sample_update() in
test/test.cpp, signed with the made-up TEST_PRIVATE_KEY (not your real key in
keys/). The test interop_encode_matches_server checks that signing and encoding
the same message in C gives the same bytes, so if server.py and the C code
drift apart, `make test` fails instead of the board printing REJECTED.

Run this again only if you change server.py's message format.
"""

from pathlib import Path

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

from server import CMD_PREFIX, build_update

# Must match TEST_PRIVATE_KEY and sample_update() in test/test.cpp.
TEST_PRIVATE_KEY = bytes(range(0x01, 0x21))
VERSION = 3
FIRMWARE = "hello, firmware!"

OUT = Path(__file__).resolve().parent / "interop_vectors.hpp"

# (C name, --attack mode, comment)
VECTORS = [
    (
        "SERVER_VALID_UPDATE",
        "none",
        "A correctly signed update. The board must accept it.",
    ),
]


def main() -> None:
    key = Ed25519PrivateKey.from_private_bytes(TEST_PRIVATE_KEY)

    out = [
        "// Generated by test/gen_interop_vectors.py from test/server.py. Do not edit.",
        "//",
        "// A command line exactly as server.py sends it, for an UPDATE with",
        f'// version {VERSION} and firmware "{FIRMWARE}", signed with TEST_PRIVATE_KEY',
        "// from test/test.cpp.",
        "#pragma once",
        "",
    ]
    for name, attack, comment in VECTORS:
        line = CMD_PREFIX + build_update(key, VERSION, FIRMWARE, attack).hex()
        out.append(f"// {comment}")
        out.append(f"static const char {name}[] =")
        # Split the long hex string over several lines of C.
        for i in range(0, len(line), 64):
            out.append(f'    "{line[i : i + 64]}"')
        out[-1] += ";"
        out.append("")

    OUT.write_text("\n".join(out))
    print(f"Wrote {OUT.relative_to(OUT.parent.parent)}")


if __name__ == "__main__":
    main()
