#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.9"
# dependencies = [
#     "cryptography>=42",
# ]
# ///
"""Make the Ed25519 keypair for Phase 3.

    uv run test/keygen.py           # make a key, or reuse the one in keys/
    uv run test/keygen.py --force   # replace it with a brand-new key

Writes:
  keys/private_key.hex  The private key. Only test/server.py reads it. It never
                        goes on a board and is never committed (see .gitignore).
  src/public_key.hpp    The public key, compiled into the firmware so the
                        boards can check signatures.

If you make a new key, rebuild and re-upload the firmware to every board, or
they will keep trusting the old public key and reject your commands.
"""
import argparse
import os
import sys
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

REPO = Path(__file__).resolve().parent.parent
PRIVATE_KEY_PATH = REPO / "keys" / "private_key.hex"
PUBLIC_HEADER_PATH = REPO / "src" / "public_key.hpp"


def load_private_key(path: Path = PRIVATE_KEY_PATH) -> Ed25519PrivateKey:
    """Read the private key that keygen.py wrote."""
    raw = bytes.fromhex(path.read_text().strip())
    return Ed25519PrivateKey.from_private_bytes(raw)


def public_bytes(key: Ed25519PrivateKey) -> bytes:
    return key.public_key().public_bytes(
        serialization.Encoding.Raw, serialization.PublicFormat.Raw
    )


def private_bytes(key: Ed25519PrivateKey) -> bytes:
    return key.private_bytes(
        serialization.Encoding.Raw,
        serialization.PrivateFormat.Raw,
        serialization.NoEncryption(),
    )


def write_private_key(key: Ed25519PrivateKey, path: Path = PRIVATE_KEY_PATH) -> None:
    """Write the key so only you can read it, from the moment the file exists."""
    path.parent.mkdir(exist_ok=True)
    if path.exists():
        path.unlink()
    # Create the file owner-only (0600) instead of fixing its mode afterwards,
    # so it's never readable by other users, even briefly. (On Windows the
    # mode is mostly ignored.)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(private_bytes(key).hex() + "\n")


def header_text(public_key: bytes) -> str:
    rows = []
    for i in range(0, len(public_key), 8):
        rows.append("    " + " ".join(f"0x{b:02x}," for b in public_key[i : i + 8]))
    body = "\n".join(rows)
    return (
        "// Generated by test/keygen.py. Do not edit; run `make keys` instead.\n"
        "#pragma once\n"
        "\n"
        "#include <stdint.h>\n"
        '#include "crypto.hpp"\n'
        "\n"
        "// The public key that signs commands. Boards only ever hold this half of\n"
        "// the keypair: it can check signatures but cannot make them.\n"
        "static const uint8_t PUBLIC_KEY[ED25519_PUBLIC_KEY_LEN] = {\n"
        f"{body}\n"
        "};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument(
        "--force", action="store_true", help="replace an existing private key"
    )
    args = parser.parse_args()

    if PRIVATE_KEY_PATH.exists() and not args.force:
        key = load_private_key()
        print(f"Using the existing private key in {PRIVATE_KEY_PATH.relative_to(REPO)}")
        print("(run with --force to make a new one)")
    else:
        key = Ed25519PrivateKey.generate()
        write_private_key(key)
        print(f"Wrote a new private key to {PRIVATE_KEY_PATH.relative_to(REPO)}")
        print("Rebuild and re-upload the firmware to every board.")

    PUBLIC_HEADER_PATH.write_text(header_text(public_bytes(key)))
    print(f"Wrote the public key to {PUBLIC_HEADER_PATH.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
